package com.bootcampexercise.module5.activity;

public class Person_I {
    private final String name;
    private final int age;

    public Person_I(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }
}
