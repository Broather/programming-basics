package com.bootcampexercise.module2.activity;

public class PrintNumWithWhile {
    /**
     * @author Markuss
     * @purpose print all odd numbers less than 100
     */
      static void main() {
        int a = 1;

        while (a < 100) {
            System.out.println(a);
            a += 2;
        }
    }
}
